print("Витязь стоит на распутье перед камнем. На камне написано:")
print("Налево пойдёшь — коня потеряешь.")
print("Направо пойдёшь — жизнь потеряешь.")
print("Прямо пойдёшь — жив будешь, да себя позабудешь.\n")

choice = input("Куда повернёт витязь? (налево / направо / прямо): ").lower()

if choice == "налево":
    print("Витязь поехал налево и потерял верного коня.")
    print("Пешком он дошёл до города, но битвы уже не будет.")
elif choice == "направо":
    print("Витязь поехал направо и сложил голову в бою.")
    print("Слава о нём осталась, но домой он не вернулся.")
elif choice == "прямо" or choice == "вперёд":
    print("Витязь поехал прямо — и остался жив.")
    print("Но забыл своё имя, свой дом и свою невесту.")
else:
    print("Витязь задумался и остался стоять на месте.")
    print("Ни славы, ни смерти, ни пути — только камень и тишина.")
